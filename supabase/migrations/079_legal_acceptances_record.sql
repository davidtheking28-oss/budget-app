-- Records what already exists in the database (created outside the repo), so the project can be rebuilt.
create table if not exists public.legal_acceptances (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  terms_version text not null,
  privacy_version text not null,
  accepted_at timestamptz not null default now(),
  age_18_confirmed boolean not null,
  unique (user_id, terms_version, privacy_version)
);
alter table public.legal_acceptances enable row level security;

create or replace function public.accept_legal_documents(p_terms_version text, p_privacy_version text, p_age_18 boolean)
returns timestamptz language plpgsql security definer set search_path to '' as $$
declare receipt timestamptz;
begin
  if auth.uid() is null then raise exception 'Authentication required' using errcode = '42501'; end if;
  if p_age_18 is distinct from true then raise exception 'Age confirmation required' using errcode = '22023'; end if;
  if p_terms_version is distinct from '2026-10-12' or p_privacy_version is distinct from '2026-10-12' then raise exception 'Unsupported legal document version' using errcode = '22023'; end if;
  insert into public.legal_acceptances(user_id, terms_version, privacy_version, age_18_confirmed) values(auth.uid(), p_terms_version, p_privacy_version, true) on conflict (user_id, terms_version, privacy_version) do nothing;
  select accepted_at into receipt from public.legal_acceptances where user_id = auth.uid() and terms_version = p_terms_version and privacy_version = p_privacy_version;
  return receipt;
end; $$;
